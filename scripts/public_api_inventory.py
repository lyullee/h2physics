"""Generate a source-only API index with AST; never import scientific modules."""

import argparse
import ast
import sys
import tomllib
from pathlib import Path


def _imports(tree):
    top, deferred = set(), set()

    def visit(node, inside_definition=False):
        nested = inside_definition or isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.Lambda))
        if isinstance(node, ast.Import):
            names = [alias.name.split(".")[0] for alias in node.names]
        elif isinstance(node, ast.ImportFrom) and node.level == 0:
            names = [(node.module or "").split(".")[0]]
        else:
            names = []
        for name in names:
            if name and name != "h2physics" and name not in sys.stdlib_module_names:
                (deferred if inside_definition else top).add(name)
        for child in ast.iter_child_nodes(node):
            visit(child, nested)

    visit(tree)
    return tuple(sorted(top)), tuple(sorted(deferred))


def _exports(tree):
    exports = None
    dynamic = False
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(isinstance(target, ast.Name) and target.id == "__all__"
                                                for target in node.targets):
            try:
                value = ast.literal_eval(node.value)
                if not isinstance(value, (list, tuple)) or any(not isinstance(name, str) for name in value):
                    raise ValueError("nonliteral exports")
                exports = tuple(value)
            except (ValueError, TypeError):
                dynamic = True
        elif isinstance(node, ast.AugAssign) and isinstance(node.target, ast.Name) and node.target.id == "__all__":
            dynamic = True
    return exports, dynamic


def inventory(root):
    rows = []
    for source in sorted((root/"src"/"h2physics").rglob("*.py")):
        tree = ast.parse(source.read_text(encoding="utf-8-sig"), filename=str(source))
        module_parts = source.relative_to(root/"src").with_suffix("").parts
        if module_parts[-1] == "__init__":
            module_parts = module_parts[:-1]
        definitions = tuple(node for node in tree.body
                            if isinstance(node, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef))
                            and not node.name.startswith("_"))
        exports, dynamic = _exports(tree)
        rows.append((source, ".".join(module_parts), definitions, exports, dynamic, _imports(tree)))
    return rows


def generate(root):
    rows = inventory(root)
    config = tomllib.loads((root/"pyproject.toml").read_text(encoding="utf-8"))
    optional = config["project"].get("optional-dependencies", {})
    count = sum(len(row[2]) for row in rows)
    lines = ["# Public Python API source index", "",
             f"Static inventory: {len(rows)} source modules and {count} public top-level class/function definitions.",
             "Generated by `python scripts/public_api_inventory.py` using AST and project metadata only.",
             "No package, provider, model, native engine or case is imported or executed.", "",
             "Direct module paths are usable Python import locations subject to their installed dependencies.",
             "Definitions are public by naming convention; this is source navigation, not a stability or physical-validity guarantee.",
             "Explicit `__all__` lists include reexports. Missing `__all__` means Python naming conventions apply.",
             "Computed or augmented export lists are flagged rather than executed.", "",
             "The import columns show non-stdlib absolute import roots. Top-level includes imports under guards/try blocks;",
             "deferred includes function bodies; class-body imports remain top-level. Static placement does not establish whether a dependency is optional:",
             "a deferred import may be required for a selected operation, and guarded imports may be optional.",
             "Native factories injected by callers may not appear as imports at all.", "",
             "## Declared installation extras", "",
             "These are exact declarations from pyproject.toml, not an inferred mapping from modules to extras.", "",
             "| Extra | Declared requirements |", "|---|---|"]
    for name, requirements in optional.items():
        lines.append(f"| `{name}` | "+", ".join(f"`{value}`" for value in requirements)+" |")
    lines += ["", "## Direct module navigation", "",
              "| Module source | Public classes/functions | Explicit exports | Import roots: top-level / deferred |",
              "|---|---|---|---|"]
    for source, module, definitions, exports, dynamic, imports in rows:
        target = "../"+source.relative_to(root).as_posix()
        symbols = ", ".join(f"[`{node.name}`]({target}#L{node.lineno})" for node in definitions) or "—"
        names = ", ".join(f"`{name}`" for name in exports) if exports is not None else "not declared"
        if dynamic:
            names += "; computed/augmented: inspect source"
        top, deferred = imports
        import_text = ", ".join(f"`{name}`" for name in top) or "—"
        import_text += " / "+(", ".join(f"`{name}`" for name in deferred) or "—")
        lines.append(f"| [`{module}`]({target}) | {symbols} | {names} | {import_text} |")
    lines += ["", "## Scope of this index", "",
              "Class methods, inherited members, generated dataclass fields, dynamically imported providers and callback semantics",
              "must be read in the linked source and domain manuals. A symbol appearing here does not establish execution,",
              "verification, validation, source rights or equipment qualification. Consult MODEL_CATALOG.md and PROGRESS.md for those states.", ""]
    return "\n".join(lines), len(rows), count


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    root = args.root.resolve()
    document, modules, definitions = generate(root)
    destination = root/"docs"/"PUBLIC_API_INDEX.md"
    destination.write_text(document, encoding="utf-8")
    print(f"Wrote {destination.name}: {modules} modules, {definitions} public definitions; AST only")


if __name__ == "__main__":
    main()

"""Check local Markdown link paths with stdlib only; never import project code."""

import argparse
import re
from pathlib import Path
from urllib.parse import unquote, urlsplit

INLINE = re.compile(r"!?\[[^\]\n]*\]\(\s*(?:<([^>\n]+)>|([^\s)]+))(?:\s+[^)\n]*)?\)")
REFERENCE = re.compile(r"^\s{0,3}\[[^\]\n]+\]:\s*(?:<([^>\n]+)>|(\S+))", re.MULTILINE)


def documents(root):
    files = set(root.glob("README*.md"))
    for name in ("docs", "requests", "research", "examples"):
        directory = root/name
        if directory.is_dir():
            files.update(directory.rglob("*.md"))
    return tuple(sorted(files))


def destinations(text):
    """Extract normal inline/image/reference destinations outside fenced code.

    Markdown is not executed or rendered. Complex generated Markdown, nested
    bracket labels and HTML links need separate inspection.
    """
    cleaned = []
    fence = None
    for line in text.splitlines(keepends=True):
        match = re.match(r"^\s{0,3}(`{3,}|~{3,})", line)
        if match:
            marker = match.group(1)[0]
            if fence is None:
                fence = marker
            elif fence == marker:
                fence = None
            cleaned.append("\n" if line.endswith("\n") else "")
        elif fence is None:
            # Inline-code examples are not live link destinations.
            cleaned.append(re.sub(r"`+[^`\n]*`+", lambda m: " "*len(m.group()), line))
        else:
            cleaned.append("\n" if line.endswith("\n") else "")
    content = "".join(cleaned)
    for pattern in (INLINE, REFERENCE):
        for match in pattern.finditer(content):
            yield content.count("\n", 0, match.start())+1, match.group(1) or match.group(2)


def audit(root):
    checked, ignored, missing = 0, 0, []
    files = documents(root)
    for source in files:
        text = source.read_text(encoding="utf-8-sig")
        for line, destination in destinations(text):
            split = urlsplit(destination)
            if split.scheme or split.netloc or not split.path:
                ignored += 1
                continue
            decoded = unquote(split.path)
            # App source links may suffix a numeric line after the extension.
            decoded = re.sub(r":\d+$", "", decoded)
            target = Path(decoded)
            if not target.is_absolute():
                target = source.parent/target
            checked += 1
            if not target.exists():
                missing.append((source.relative_to(root).as_posix(), line, decoded))
    return files, checked, ignored, missing


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    root = args.root.resolve()
    files, checked, ignored, missing = audit(root)
    lines = ["# Local document link audit", "",
             f"Checked {checked} local link destinations across {len(files)} Markdown files; "
             f"{len(missing)} missing paths. Ignored {ignored} remote/scheme/fragment-only destinations.",
             "Generated by `python scripts/audit_document_links.py` using the Python standard library only.", "",
             "Scope: repository README*.md plus Markdown under docs, requests, research and examples.",
             "Inline links, images and reference destinations are inspected outside fenced and inline code.",
             "URL path escapes and angle-wrapped destinations are decoded; local file/directory existence is checked.",
             "Web, mail, app schemes and fragment-only links are skipped. Fragment anchors are not validated.",
             "This source scan does not render Markdown, follow redirects or validate nested-label/HTML/generated links.", "",
             "| Document location | Missing local path |", "|---|---|"]
    for source, line, destination in missing:
        safe = destination.replace("|", "\\|").replace("`", "&#96;")
        lines.append(f"| `{source}:{line}` | `{safe}` |")
    if not missing:
        lines.append("| — | No missing local paths found in the inspected link syntax |")
    (root/"docs"/"DOCUMENT_LINK_AUDIT.md").write_text("\n".join(lines)+"\n", encoding="utf-8")
    print(f"Local Markdown paths: {checked} checked, {len(missing)} missing across {len(files)} files")
    for source, line, destination in missing:
        print(f"{source}:{line}: {destination}")
    return 1 if missing else 0


if __name__ == "__main__":
    raise SystemExit(main())

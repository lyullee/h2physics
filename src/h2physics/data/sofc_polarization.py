"""Source-hash-bound reader for four licensed Mendeley SOFC curve tables."""

import hashlib
from dataclasses import dataclass
from pathlib import Path
from io import StringIO

import numpy as np

from ..core import Origin
from ..observations import ObservationTable
from .polarization import load_polarization_grid

DOI = "10.17632/j8b9v4cb9d.1"
_FILES = {
    "Ui_30H2_10H2O_60N2.txt": (12196, "2b85caac300d4094f26f5acb3499ead26c78154d7ebad81d869c5514992341c9"),
    "Ui_50H2_0H2O_50N2.txt": (17753, "d76a1ec0888e5960a96c80023eb3c73dded77bd43bb52bf849532f1e1f34d102"),
    "Ui_50H2_10H2O_40N2.txt": (17759, "eac5c114ecec8747169dd2f260a599a8f8fdcaeddcea8856ab1fd44161cf4e33"),
    "Ui_50H2_20H2O_30N2.txt": (17774, "46c5478fcad9a077b62a25234e4d048ea22b769eed79782349e32ec8deeeb8ed"),
}


def _parse(path: Path, payload: bytes, digest: str) -> tuple[ObservationTable, ...]:
    source_id = f"{DOI}:{path.name}:{digest}"
    text = payload.decode("cp1252", errors="strict")
    return load_polarization_grid(
        StringIO(text), source_id=source_id, group_prefix=path.stem,
        temperature_unit="degC", current_density_unit="mA/cm2", voltage_unit="V",
        voltage_origin=Origin.UNRESOLVED,
    )


@dataclass(frozen=True, slots=True)
class SOFCPolarizationData:
    """One file's original hash and parsed temperature-condition tables."""

    source_path: Path
    source_sha256: str
    curves: tuple[ObservationTable, ...]

    def require_current(self):
        path = Path(self.source_path).resolve()
        if path.name not in _FILES or path != self.source_path:
            raise ValueError("SOFC source path/file identity changed")
        expected_size, expected_sha = _FILES[path.name]
        payload = path.read_bytes()
        digest = hashlib.sha256(payload).hexdigest()
        if len(payload) != expected_size or digest != expected_sha or digest != self.source_sha256:
            raise ValueError("SOFC source file differs from its Mendeley v1 receipt")
        rebuilt = _parse(path, payload, digest)
        if (len(rebuilt) != len(self.curves)
                or any(actual.content_sha256 != retained.content_sha256
                       for actual, retained in zip(rebuilt, self.curves, strict=True))):
            raise ValueError("SOFC parsed tables differ from the retained source bytes")
        return self


def load_sofc_polarization_data(path: str | Path) -> SOFCPolarizationData:
    """Load one exact Mendeley v1 polarization file after byte/hash verification.

    Mendeley states that files combine experimental SOFC curves and curves
    generated by a multiphysics model. Voltage origins therefore stay unresolved.
    """
    source = Path(path).resolve()
    if source.name not in _FILES or source.is_symlink() or not source.is_file():
        raise ValueError("Path must identify one of the four listed SOFC v1 files")
    size, expected_sha = _FILES[source.name]
    payload = source.read_bytes()
    digest = hashlib.sha256(payload).hexdigest()
    if len(payload) != size or digest != expected_sha:
        raise ValueError("SOFC v1 file length or SHA-256 differs from the acquired provenance manifest")
    curves = _parse(source, payload, digest)
    return SOFCPolarizationData(source, digest, curves)


